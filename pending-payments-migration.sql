-- Prime Auto Motors: pending / installment payments
-- Run once in Supabase SQL Editor before using the Pending Payments page.

create table if not exists public.pending_sales (
  id text primary key,
  customer text not null,
  total_amount numeric(12,2) not null check (total_amount > 0),
  amount_paid numeric(12,2) not null default 0 check (amount_paid >= 0),
  status text not null default 'pending' check (status in ('pending','partial','paid')),
  notes text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.pending_sale_items (
  id bigint generated by default as identity primary key,
  pending_sale_id text not null references public.pending_sales(id) on delete cascade,
  product_code text not null,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  cost_price numeric(12,2) not null default 0 check (cost_price >= 0)
);

create table if not exists public.pending_sale_payments (
  id bigint generated by default as identity primary key,
  pending_sale_id text not null references public.pending_sales(id) on delete cascade,
  amount numeric(12,2) not null check (amount > 0),
  payment_method text not null default 'Cash' check (payment_method in ('Cash','Card','Koko')),
  paid_at timestamptz not null default now(),
  notes text not null default ''
);

create index if not exists pending_sales_status_created_idx on public.pending_sales(status, created_at desc);
create index if not exists pending_sale_items_sale_idx on public.pending_sale_items(pending_sale_id);
create index if not exists pending_sale_payments_sale_date_idx on public.pending_sale_payments(pending_sale_id, paid_at desc);

alter table public.pending_sales enable row level security;
alter table public.pending_sale_items enable row level security;
alter table public.pending_sale_payments enable row level security;

drop policy if exists "Authenticated users manage pending sales" on public.pending_sales;
create policy "Authenticated users manage pending sales" on public.pending_sales
  for all to authenticated using (true) with check (true);
drop policy if exists "Authenticated users manage pending sale items" on public.pending_sale_items;
create policy "Authenticated users manage pending sale items" on public.pending_sale_items
  for all to authenticated using (true) with check (true);
drop policy if exists "Authenticated users manage pending sale payments" on public.pending_sale_payments;
create policy "Authenticated users manage pending sale payments" on public.pending_sale_payments
  for all to authenticated using (true) with check (true);

grant select, insert, update, delete on public.pending_sales to authenticated;
grant select, insert, update, delete on public.pending_sale_items to authenticated;
grant select, insert, update, delete on public.pending_sale_payments to authenticated;
grant usage, select on sequence public.pending_sale_items_id_seq, public.pending_sale_payments_id_seq to authenticated;

create or replace function public.create_pending_pos_sale(
  p_sale_id text,
  p_customer text,
  p_items jsonb,
  p_notes text default ''
) returns text
language plpgsql
set search_path = public
as $$
declare
  item jsonb;
  v_sku text;
  v_qty integer;
  v_price numeric(12,2);
  v_total numeric(12,2) := 0;
  v_name text;
  v_cost numeric(12,2);
  v_available integer;
begin
  if auth.uid() is null then raise exception 'You must be signed in.'; end if;
  if coalesce(trim(p_sale_id),'') = '' then raise exception 'Pending sale reference is required.'; end if;
  if coalesce(trim(p_customer),'') = '' then raise exception 'Customer name is required for a pending sale.'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Add at least one product.';
  end if;

  for item in select value from jsonb_array_elements(p_items) loop
    v_sku := trim(coalesce(item->>'sku',''));
    v_qty := (item->>'quantity')::integer;
    v_price := (item->>'unit_price')::numeric;
    if v_sku = '' or v_qty < 1 or v_price < 0 then raise exception 'Invalid product or quantity.'; end if;
    if not exists (select 1 from public.stock where product_code = v_sku) then
      raise exception 'Product % was not found in stock.', v_sku;
    end if;
    v_total := v_total + v_qty * v_price;
  end loop;
  if v_total <= 0 then raise exception 'Pending sale total must be greater than zero.'; end if;

  insert into public.pending_sales(id, customer, total_amount, notes)
  values (p_sale_id, trim(p_customer), v_total, coalesce(p_notes,''));

  for item in select value from jsonb_array_elements(p_items) loop
    v_sku := trim(coalesce(item->>'sku',''));
    v_qty := (item->>'quantity')::integer;
    v_price := (item->>'unit_price')::numeric;

    update public.stock
       set quantity = quantity - v_qty, updated_at = now()
     where product_code = v_sku and quantity >= v_qty
     returning product_name, cost_price into v_name, v_cost;

    if not found then
      raise exception 'Not enough stock for product %. Please refresh stock and try again.', v_sku;
    end if;

    insert into public.pending_sale_items(pending_sale_id, product_code, product_name, quantity, unit_price, cost_price)
    values (p_sale_id, v_sku, v_name, v_qty, v_price, coalesce(v_cost,0));
  end loop;

  return p_sale_id;
end;
$$;

grant execute on function public.create_pending_pos_sale(text,text,jsonb,text) to authenticated;

create or replace function public.validate_pending_payment()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_total numeric(12,2);
  v_already_paid numeric(12,2);
begin
  if new.amount <= 0 then raise exception 'Payment must be greater than zero.'; end if;
  select total_amount into v_total from public.pending_sales where id = new.pending_sale_id for update;
  if not found then raise exception 'Pending sale not found.'; end if;
  select coalesce(sum(amount),0) into v_already_paid
    from public.pending_sale_payments
   where pending_sale_id = new.pending_sale_id
     and (tg_op = 'INSERT' or id <> new.id);
  if v_already_paid + new.amount > v_total then
    raise exception 'Payment exceeds the remaining balance of %.', (v_total - v_already_paid);
  end if;
  return new;
end;
$$;

drop trigger if exists validate_pending_payment_before_write on public.pending_sale_payments;
create trigger validate_pending_payment_before_write
before insert or update of amount, pending_sale_id on public.pending_sale_payments
for each row execute function public.validate_pending_payment();

create or replace function public.sync_pending_sale_paid_total()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_sale_id text;
  v_paid numeric(12,2);
  v_total numeric(12,2);
begin
  v_sale_id := case when tg_op = 'DELETE' then old.pending_sale_id else new.pending_sale_id end;
  select total_amount into v_total from public.pending_sales where id = v_sale_id;
  if not found then
    if tg_op = 'DELETE' then return old; else return new; end if;
  end if;
  select coalesce(sum(amount),0) into v_paid from public.pending_sale_payments where pending_sale_id = v_sale_id;
  update public.pending_sales
     set amount_paid = v_paid,
         status = case when v_paid >= v_total then 'paid' when v_paid > 0 then 'partial' else 'pending' end
   where id = v_sale_id;
  if tg_op = 'DELETE' then return old; else return new; end if;
end;
$$;

drop trigger if exists sync_pending_sale_paid_total_after_write on public.pending_sale_payments;
create trigger sync_pending_sale_paid_total_after_write
after insert or update or delete on public.pending_sale_payments
for each row execute function public.sync_pending_sale_paid_total();
